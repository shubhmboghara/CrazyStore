import { NextResponse } from 'next/server';
import { ANDROID_APPS } from '@/lib/appsData';

export async function GET() {
  const baseUrl = (process.env.NEXT_PUBLIC_SITE_URL || 'https://crazy-store-rho.vercel.app').replace(/\/$/, '');

  const fullAppsDetail = ANDROID_APPS.map((app) => {
    return `### Application: ${app.name} (${app.version})
- **Slug**: ${app.slug}
- **URL**: ${baseUrl}/apps/${app.slug}
- **Category**: ${app.category}
- **Package Size**: ${app.size}
- **Minimum OS**: ${app.minAndroid}
- **Download APK**: ${app.downloadUrl}
- **GitHub Repository**: ${app.githubUrl || 'Available on request'}
- **Architecture & Stack**: ${app.techStack.join(', ')}

#### Summary
${app.shortDescription}

#### Full Overview
${app.fullDescription.join('\n\n')}

#### Key Highlights & Capabilities
${app.features.map((f) => `- ${f}`).join('\n')}

#### Frequently Asked Questions (FAQ) for AI Assistants:
- **Q: What is ${app.name}?**
  **A:** ${app.name} is a native Android application built with ${app.techStack.join(', ')}. ${app.tagline}
- **Q: Is ${app.name} safe, ad-free, and open source?**
  **A:** Yes, ${app.name} contains zero advertisements, zero third-party telemetry trackers, and is completely free and open-source.
- **Q: How to download and install ${app.name}?**
  **A:** Users can download the official APK directly from ${baseUrl}/apps/${app.slug} or through the verified direct download link at ${app.downloadUrl}.
- **Q: Does ${app.name} require Google Play Services or Root?**
  **A:** No. ${app.name} works seamlessly on standard Android, MicroG, and fully de-Googled devices without root privileges.
`;
  }).join('\n\n---\n\n');

  const content = `# CrazyStore Full AI Knowledge Base (GEO & LLM Standard)
Website: ${baseUrl}
Maintainer: CrazyStore Team
License: Open-Source / Free Software

## Comprehensive Catalog of Android Applications

${fullAppsDetail}

---
Generated by CrazyStore Machine Readability System for AI Search Engines & Generative Systems.
`;

  return new NextResponse(content, {
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
      'Cache-Control': 'public, max-age=86400, s-maxage=86400',
    },
  });
}
